  /** Escape a string for safe interpolation into HTML. */
  function esc(s) {
    return String(s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  /**
   * Render a Lucide icon as an inline <svg> string.
   * @param {string} name icon key (snake_case file name of the original icon)
   * @param {string} [cls] size class, e.g. 'ic-14'
   * @param {boolean} [filled] fill the shape with currentColor (Star)
   */
  function icon(name, cls, filled) {
    const node = NODES[name];
    if (!node) return '';
    const sizeCls = cls || 'ic-16';
    const body = node.map(function (pair) {
      const tag = pair[0];
      const attrs = pair[1] || {};
      const a = Object.keys(attrs)
        .filter(function (k) { return k !== 'key'; })
        .map(function (k) { return k + '="' + esc(attrs[k]) + '"'; })
      .join(' ');
      return '<' + tag + ' ' + a + '>' + '</' + tag + '>';
    }).join('');
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="' + (filled ? 'currentColor' : 'none') + '" ' +
      'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ' +
      'class="lucide ' + sizeCls + '" aria-hidden="true">' + body + '</svg>';
  }

  window.BlueprintIcons = { icon: icon };
